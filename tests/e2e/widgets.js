// Interactive illustrations (tracks 2 and 3): every widget renders with a data badge, every
// slider is keyboard-operable and updates a polite live region, key behaviours compute the
// right numbers, nothing overflows at 320px, and reduced motion skips the animations.
// Run with: NODE_PATH=$(npm root -g) node tests/e2e/widgets.js   (server on BASE, default :3300)
const H = require("./helpers");
const { chromium, BASE, check } = H;

const NEW_LESSONS = H.ALL_LESSONS.filter((l) => l.trackId !== "market-foundations");
const statusText = (w) => w.locator("[role=status]").first().textContent();

(async () => {
  const browser = await chromium.launch();

  // 1. Every widget on every new lesson: badge, labelled controls, keyboard → live region.
  for (const [label, opts] of [["desktop", H.DESKTOP], ["w320", H.NARROW]]) {
    const ctx = await browser.newContext(opts);
    const page = await ctx.newPage();
    const logs = []; H.watchConsole(page, logs);
    // Tracks 2 and 3 unlock after Market Foundations (lessons + assessment): store that state first.
    await H.unlockTracks(page);
    let widgets = 0, sliders = 0;
    const unlabelled = [], deaf = [], overflow = [], unbadged = [], tiny = [];
    let textCount = 0;
    for (const l of NEW_LESSONS) {
      await page.goto(BASE + l.url, { waitUntil: "networkidle" });
      await page.waitForTimeout(150);
      const ws = page.locator("[data-widget]");
      const n = await ws.count();
      if (n === 0) unbadged.push(`${l.id}: no widget`);
      for (let i = 0; i < n; i++) {
        const w = ws.nth(i);
        widgets++;
        await w.scrollIntoViewIfNeeded();
        // Track 6 charts are generated by a seeded simulator, so they carry the "Simulated" badge.
        const badge = await w.locator("span[title]").filter({ hasText: /Sample|Computed|Simulated/ }).count();
        if (!badge) unbadged.push(`${l.id}#${i}`);
        const ov = await w.evaluate((el) => { const r = el.getBoundingClientRect(); return { r: r.right, vw: document.documentElement.clientWidth, sw: el.scrollWidth, cw: el.clientWidth }; });
        if (ov.r > ov.vw + 1 || ov.sw > ov.cw + 1) overflow.push(`${l.id}#${i} right=${Math.round(ov.r)}/${ov.vw} scroll=${ov.sw}/${ov.cw}`);
        // every form control has an accessible name
        const names = await w.locator("input:not([type=radio]), select").evaluateAll((els) => els.map((e) => (e.labels && e.labels.length ? e.labels[0].textContent : e.getAttribute("aria-label")) || ""));
        names.forEach((nm, k) => { if (!nm.trim()) unlabelled.push(`${l.id}#${i} control ${k}`); });
        // keyboard: nudge the first slider and expect the live region to change
        const r = w.locator("input[type=range]");
        const rc = await r.count();
        sliders += rc;
        if (rc) {
          const before = await statusText(w);
          await r.first().focus();
          for (let k = 0; k < 6; k++) await page.keyboard.press("ArrowRight");
          await page.waitForTimeout(80);
          let after = await statusText(w);
          if (after === before) { for (let k = 0; k < 12; k++) await page.keyboard.press("ArrowLeft"); await page.waitForTimeout(80); after = await statusText(w); }
          const vt = await r.first().getAttribute("aria-valuetext");
          if (after === before && !vt) deaf.push(`${l.id}#${i}`);
        }
        // diagram text renders at a readable size (about 11–13 CSS px) whatever the width
        const sizes = await w.evaluate((el) => [...el.querySelectorAll("svg[viewBox] text")].filter((t) => getComputedStyle(t).display !== "none" && t.textContent.trim()).map((t) => {
          const svg = t.ownerSVGElement; const vb = svg.viewBox.baseVal;
          const k = svg.getBoundingClientRect().width / vb.width;
          return { px: parseFloat(getComputedStyle(t).fontSize) * k, txt: t.textContent.trim().slice(0, 12) };
        }));
        for (const z of sizes) if (z.txt !== "→" && (z.px < 10.4 || z.px > 14)) tiny.push(`${l.id}#${i} "${z.txt}" ${z.px.toFixed(1)}px`);
        textCount += sizes.length;
        const live = await w.locator("[role=status][aria-live=polite]").count();
        if (!live) deaf.push(`${l.id}#${i} (no live region)`);
      }
    }
    check(`[${label}] every new lesson has at least one widget, each with a Sample/Computed/Simulated badge (${widgets} widgets)`, unbadged.length === 0 && widgets >= NEW_LESSONS.length, unbadged.join("; "));
    check(`[${label}] all widget controls are labelled`, unlabelled.length === 0, unlabelled.slice(0, 5).join("; "));
    check(`[${label}] keyboard moves sliders and results are announced (${sliders} sliders)`, deaf.length === 0, deaf.join("; "));
    check(`[${label}] no widget overflows its box or the viewport`, overflow.length === 0, overflow.slice(0, 5).join("; "));
    check(`[${label}] diagram text renders at 10.5–14px (${textCount} labels)`, tiny.length === 0 && textCount > 30, tiny.slice(0, 6).join("; "));
    check(`[${label}] no console errors on new lessons`, logs.length === 0, logs.slice(0, 3).join(" | "));
    await ctx.close();
  }

  // 2. Behaviour checks (desktop)
  const ctx = await browser.newContext(H.DESKTOP);
  const page = await ctx.newPage();
  await H.unlockTracks(page); // tracks 2 and 3 are gated on Market Foundations
  const W = (title) => page.locator("[data-widget]", { hasText: title });

  // Spread round trip: price never moves, the loss equals the spread
  await page.goto(BASE + H.lessonUrl("fx-quotes"), { waitUntil: "networkidle" });
  {
    const w = W("Buy and sell straight back");
    await w.getByRole("button", { name: "1. Buy now" }).click();
    await w.getByRole("button", { name: "2. Sell straight back" }).click();
    const t = await statusText(w);
    check("spread toy: mini lot, 1.0 pip spread → round trip costs $1.00", /cost \$1\.00/.test(t), t);
  }
  // Rate converter: moving the rate up says the euro strengthened
  {
    const w = W("Drag the exchange rate");
    const s = w.getByRole("slider").first();
    await s.focus(); for (let k = 0; k < 40; k++) await page.keyboard.press("ArrowRight");
    const t = await statusText(w);
    check("rate converter: higher rate → euro strengthened", /euro has strengthened/.test(t), t.slice(0, 120));
  }

  // Pip calculator: 0.1 lot EUR/USD = $1/pip; USD/JPY uses division
  await page.goto(BASE + H.lessonUrl("fx-pips-lots"), { waitUntil: "networkidle" });
  {
    const w = W("Pip value calculator");
    const txt = await w.textContent();
    check("pip calculator: 0.1 lot EUR/USD → $1.00 per pip", /1 pip in USD \(account\)\$1\.00/.test(txt), txt.slice(0, 200));
    await w.getByText("USD/JPY", { exact: true }).click();
    const t2 = await statusText(w);
    check("pip calculator: USD/JPY working divides by the rate", /÷ 150/.test(t2), t2);
  }

  // Margin simulator: reduced motion jumps straight to stop-out
  {
    const rctx = await browser.newContext({ ...H.DESKTOP, reducedMotion: "reduce" });
    const p = await rctx.newPage();
    await H.unlockTracks(p);
    await p.goto(BASE + H.lessonUrl("fx-leverage-margin"), { waitUntil: "networkidle" });
    const w = p.locator("[data-widget]", { hasText: "Leverage and margin simulator" });
    await w.getByRole("button", { name: /Play a falling market/ }).click();
    await p.waitForTimeout(150);
    const t = await w.locator("[role=status]").first().textContent();
    check("margin simulator (reduced motion): Play goes straight to a stop-out", /Stop-out/.test(t), t.slice(0, 160));
    // too big a position at 1:1 cannot be opened
    await w.getByText("1:1", { exact: true }).click();
    const t2 = await w.locator("[role=status]").first().textContent();
    check("margin simulator: 0.2 lots at 1:1 needs more than the $1,000 account", /Not enough margin/.test(t2), t2.slice(0, 120));
    await rctx.close();
  }
  // Margin simulator with motion: Play animates over time (not instant) and ends in stop-out
  {
    await page.goto(BASE + H.lessonUrl("fx-leverage-margin"), { waitUntil: "networkidle" });
    const w = W("Leverage and margin simulator");
    await w.getByRole("button", { name: /Play a falling market/ }).click();
    await page.waitForTimeout(200);
    const mid = await statusText(w);
    await page.waitForTimeout(4000);
    const end = await statusText(w);
    check("margin simulator (motion): animates, then stops out", !/Stop-out/.test(mid) && /Stop-out/.test(end), `mid="${mid.slice(0, 60)}" end="${end.slice(0, 60)}"`);
  }

  // Drivers toy: the gauge needle points the same way as the text, in every scenario
  await page.goto(BASE + H.lessonUrl("fx-drivers"), { waitUntil: "networkidle" });
  {
    const w = W("Cause and effect: what moves a currency");
    const bad = [];
    let seen = 0;
    const probe = async (what) => {
      const line = w.locator("svg[data-gauge] line");
      const angle = +(await line.getAttribute("data-angle"));
      const txt = await w.textContent();
      const says = /tends to strengthen/.test(txt) ? "stronger" : /tends to weaken/.test(txt) ? "weaker" : "flat";
      const points = angle > 1 ? "stronger" : angle < -1 ? "weaker" : "flat";
      // the right-hand label is "stronger": a positive rotate() turns the needle clockwise, to the right
      const tr = await line.getAttribute("transform");
      if (says !== points || !tr.includes(`rotate(${angle} `)) bad.push(`${what}: text ${says}, needle ${angle}°`);
      seen++;
    };
    for (const d of ["Interest rates", "Inflation", "Risk mood", "Trade flows"]) {
      await w.getByText(d, { exact: true }).click();
      for (const s of await w.getByRole("slider").all()) {
        for (const key of ["Home", "End"]) { await s.focus(); await page.keyboard.press(key); await probe(`${d} ${key}`); }
      }
      if (d === "Risk mood") for (const m of ["Risk-on (confident)", "Risk-off (fearful)"]) { await w.getByText(m).click(); await probe(m); }
    }
    check(`drivers toy: needle direction matches the text in ${seen} scenarios`, bad.length === 0 && seen >= 10, bad.join("; "));
    const labels = await w.evaluate((el) => {
      const svg = el.querySelector("svg[data-gauge]").getBoundingClientRect();
      const spans = [...el.querySelectorAll("svg[data-gauge] + div span")].map((s) => s.getBoundingClientRect());
      return { overlap: spans.some((r) => r.top < svg.bottom - 1), n: spans.length, sizes: [...el.querySelectorAll("svg[data-gauge] + div span")].map((s) => parseFloat(getComputedStyle(s).fontSize)) };
    });
    check("drivers toy: weaker/stronger labels sit below the arc, at 11px", labels.n === 2 && !labels.overlap && labels.sizes.every((x) => x >= 11), JSON.stringify(labels));
  }

  // Session clock renders after mount with the computed badge
  await page.goto(BASE + H.lessonUrl("fx-sessions"), { waitUntil: "networkidle" });
  {
    const w = W("24-hour session timeline");
    const t = await statusText(w);
    check("session clock: shows open sessions for a sample Wednesday", /your time:/.test(t), t.slice(0, 120));
    check("session clock: carries the Computed badge", (await w.locator("span[title]").filter({ hasText: "Computed" }).count()) === 1);
  }

  // Pair explorer: same currency twice is rejected, JPY quote → 0.01 pip
  await page.goto(BASE + H.lessonUrl("fx-pairs"), { waitUntil: "networkidle" });
  {
    const w = W("Build a pair");
    await w.getByLabel("Second currency").selectOption("JPY");
    let txt = await w.textContent();
    check("pair explorer: EUR + JPY → EUR/JPY, minor, pip 0.01", /EUR\/JPY/.test(txt) && /Minor/.test(txt) && /0\.01/.test(txt), txt.slice(0, 200));
    await w.getByLabel("First currency").selectOption("TRY");
    txt = await w.textContent();
    check("pair explorer: TRY + JPY → TRY/JPY exotic", /TRY\/JPY/.test(txt) && /Exotic/.test(txt));
    await w.getByLabel("First currency").selectOption("JPY");
    check("pair explorer: same currency twice is refused", /two different currencies/.test(await statusText(w)));
  }

  // Order book: market buy walks the book; limit below the ask rests
  await page.goto(BASE + H.lessonUrl("si-exchanges"), { waitUntil: "networkidle" });
  {
    const w = W("Send an order into the book");
    await w.getByRole("button", { name: "Send order" }).click(); // market buy 500
    let t = await statusText(w);
    check("order book: market buy 500 → filled at $50.02 and $50.03, avg $50.024", /Filled/.test(t) && /300 at \$50\.02, 200 at \$50\.03/.test(t) && /Average price \$50\.024/.test(t), t);
    await w.getByText("Limit", { exact: true }).click();
    t = await w.textContent();
    await w.getByRole("button", { name: "Send order" }).click(); // limit buy 500 @ 50.00 (below the best ask 50.03 now)
    t = await statusText(w);
    check("order book: limit buy below the ask rests in the book", /Resting/.test(t), t);
    await w.getByRole("button", { name: "Reset book" }).click();
    check("order book: reset restores the starting book", /Choose an order/.test(await statusText(w)));
  }

  // Index builder: price-weighted vs split
  await page.goto(BASE + H.lessonUrl("si-index-calc"), { waitUntil: "networkidle" });
  {
    const w = W("Index builder");
    const before = await w.locator("dl").first().textContent();
    await w.getByLabel(/4-for-1 share split/).check();
    const after = await w.locator("dl").first().textContent();
    check("index builder: a split changes the price-weighted result only", before !== after, `${before} → ${after}`);
  }

  // Earnings: loss → P/E n/a
  await page.goto(BASE + H.lessonUrl("si-earnings"), { waitUntil: "networkidle" });
  {
    const w = W("Earnings beat or miss");
    const costs = w.getByRole("slider", { name: /All costs/ });
    await costs.focus(); await page.keyboard.press("End");
    const txt = await w.textContent();
    check("earnings toy: costs above revenue → P/E shown as n/a (loss)", /n\/a/.test(txt) && /Not meaningful for a loss/.test(txt));
  }

  // Corporate actions: split keeps value
  await page.goto(BASE + H.lessonUrl("si-dividends-actions"), { waitUntil: "networkidle" });
  {
    const w = W("Split, dividend or buyback");
    const txt = await w.textContent();
    check("corporate actions: 2-for-1 split keeps $3,000", /\$3,000 → \$3,000/.test(txt), txt.slice(0, 200));
    await w.getByText("Dividend", { exact: true }).click();
    check("corporate actions: dividend tab explains the ex-date drop", /ex-dividend date/.test(await statusText(w)));
  }

  // Callout cross-link from the leverage lesson to the ESMA disclosure in track 1
  await page.goto(BASE + H.lessonUrl("fx-leverage-margin"), { waitUntil: "networkidle" });
  {
    const a = page.getByRole("link", { name: /what regulators found about retail CFD losses/ });
    check("leverage lesson links back to the ESMA findings lesson", (await a.getAttribute("href")) === H.lessonUrl("trading-vs-investing"));
  }

  // Dashboard carries on into track 2 once Market Foundations is complete
  {
    const c2 = await browser.newContext(H.DESKTOP);
    const now = new Date().toISOString();
    const lessons = {};
    for (const l of H.ALL_LESSONS.filter((x) => x.trackId === "market-foundations")) lessons[l.id] = { sectionsRead: {}, exerciseCompletedAt: now, quizAttempts: [{ at: now, correct: 5, total: 5 }], reflection: null };
    // sections: read from the rendered lesson pages (ids are in the DOM as section[id])
    const p = await c2.newPage();
    for (const l of H.ALL_LESSONS.filter((x) => x.trackId === "market-foundations")) {
      await p.goto(BASE + l.url, { waitUntil: "domcontentloaded" });
      const ids = await p.locator("article section[id]").evaluateAll((ss) => ss.map((s) => s.id));
      lessons[l.id].sectionsRead = Object.fromEntries(ids.map((i) => [i, now]));
    }
    // Completing the lessons is no longer enough to finish the track: the stored state also
    // carries a passed Market Foundations assessment (the track gate added in Phase 2 step 1).
    await p.evaluate(([k, v]) => localStorage.setItem(k, v), [H.KEY, JSON.stringify({ version: 1, updatedAt: now, lessons, assessments: { "market-foundations": { attempts: [H.passedAttempt("market-foundations", now)], remediation: {}, draft: null } } })]);
    await p.goto(BASE + "/", { waitUntil: "networkidle" });
    const lp = await p.locator("section", { has: p.getByRole("heading", { name: "Learning progress" }) }).textContent();
    const nl = p.locator("section", { has: p.getByRole("heading", { name: "Recommended next lesson" }) });
    const href = await nl.getByRole("link").last().getAttribute("href");
    const journey = await p.locator("main").textContent();
    check("dashboard: after Market Foundations, Learning progress shows Forex Foundations 0/7", /0\/7/.test(lp) && /Forex Foundations/.test(lp), lp.slice(0, 160));
    check("dashboard: recommends the first forex lesson", href === H.lessonUrl("fx-quotes"), href);
    check("dashboard: journey stage is Learning and names the current track", /Now working through Forex Foundations: 0 of 7/.test(journey));
    await c2.close();
  }

  await ctx.close();
  await browser.close();
  H.summary();
})().catch((e) => { console.error(e); process.exitCode = 2; });
